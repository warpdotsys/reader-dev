    fn is_lam_alef(&self, b: u8) -> u8 {
        if b == 0xb2 || b == 0xb3 {
            0x47
        } else if b == 0xb4 || b == 0xb5 {
            0x49
        } else if b == 0xb8 || b == 0xb9 {
            0x56
        } else {
            0x00
        }
    }

