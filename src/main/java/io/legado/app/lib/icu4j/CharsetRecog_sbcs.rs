pub struct NGramParser {
    //        private static final int N_GRAM_SIZE = 3;
    //        private static final int N_GRAM_MASK = 0xFFFFFF;
    byte_index: i32,
    ngram: i32,
    ngram_list: &'static [i32],
    byte_map: &'static [u8],
    ngram_count: i32,
    hit_count: i32,
    space_char: u8,
}

impl NGramParser {
    // public NGramParser(int[] theNgramList, byte[] theByteMap) {
    //     ngramList = theNgramList;
    //     byteMap = theByteMap;
    //
    //     ngram = 0;
    //
    //     ngramCount = hitCount = 0;
    // }
    pub fn new(the_ngram_list: &'static [i32], the_byte_map: &'static [u8]) -> NGramParser {
        NGramParser {
            byte_index: 0,
            ngram: 0,
            ngram_list: the_ngram_list,
            byte_map: the_byte_map,
            ngram_count: 0,
            hit_count: 0,
            space_char: 0x20,
        }
    }

    /*
     * Binary search for value in table, which must have exactly 64 entries.
     */
    // private static int search(int[] table, int value) {
    fn search(table: &[i32], value: i32) -> i32 {
        let mut index = 0;

        // if (table[index + 32] <= value) {
        //     index += 32;
        // }
        if table[index + 32] <= value {
            index += 32;
        }

        // if (table[index + 16] <= value) {
        //     index += 16;
        // }
        if table[index + 16] <= value {
            index += 16;
        }

        // if (table[index + 8] <= value) {
        //     index += 8;
        // }
        if table[index + 8] <= value {
            index += 8;
        }

        // if (table[index + 4] <= value) {
        //     index += 4;
        // }
        if table[index + 4] <= value {
            index += 4;
        }

        // if (table[index + 2] <= value) {
        //     index += 2;
        // }
        if table[index + 2] <= value {
            index += 2;
        }

        // if (table[index + 1] <= value) {
        //     index += 1;
        // }
        if table[index + 1] <= value {
            index += 1;
        }

        // if (table[index] > value) {
        //     index -= 1;
        // }
        if table[index] > value {
            index -= 1;
        }

        // if (index < 0 || table[index] != value) {
        //     return -1;
        // }
        if index < 0 || table[index] != value {
            return -1;
        }

        // return index;
        index as i32
    }

    // private void lookup(int thisNgram) {
    //     ngramCount += 1;
    //
    //     if (search(ngramList, thisNgram) >= 0) {
    //         hitCount += 1;
    //     }
    //
    // }
    fn lookup(&mut self, this_ngram: i32) {
        self.ngram_count += 1;

        if Self::search(self.ngram_list, this_ngram) >= 0 {
            self.hit_count += 1;
        }
    }

    // protected void addByte(int b) {
    //     ngram = ((ngram << 8) + (b & 0xFF)) & N_GRAM_MASK;
    //     lookup(ngram);
    // }
    fn add_byte(&mut self, b: i32) {
        self.ngram = ((self.ngram << 8) + (b & 0xFF)) & 0xFFFFFF;
        self.lookup(self.ngram);
    }

    // private int nextByte(CharsetDetector det) {
    //     if (byteIndex >= det.fInputLen) {
    //         return -1;
    //     }
    //
    //     return det.fInputBytes[byteIndex++] & 0xFF;
    // }
    fn next_byte(&mut self, det: &CharsetDetector) -> i32 {
        if self.byte_index >= det.f_input_len_access() {
            return -1;
        }

        let result = det.f_input_bytes_access()[self.byte_index as usize] & 0xFF;
        self.byte_index += 1;
        result as i32
    }

    // protected void parseCharacters(CharsetDetector det) {
    //     int b;
    //     boolean ignoreSpace = false;
    //
    //     while ((b = nextByte(det)) >= 0) {
    //         byte mb = byteMap[b];
    //
    //         // TODO: 0x20 might not be a space in all character sets...
    //         if (mb != 0) {
    //             if (!(mb == spaceChar && ignoreSpace)) {
    //                 addByte(mb);
    //             }
    //
    //             ignoreSpace = (mb == spaceChar);
    //         }
    //     }
    //
    // }
    fn parse_characters(&mut self, det: &CharsetDetector) {
        let mut b: i32;
        let mut ignore_space = false;

        // while ((b = nextByte(det)) >= 0) {
        loop {
            b = self.next_byte(det);
            if b < 0 {
                break;
            }
            let mb = self.byte_map[b as usize];

            // TODO: 0x20 might not be a space in all character sets...
            if mb != 0 {
                if !(mb == self.space_char && ignore_space) {
                    self.add_byte(mb as i32);
                }

                ignore_space = (mb == self.space_char);
            }
        }
    }

    // public int parse(CharsetDetector det) {
    //     return parse(det, (byte) 0x20);
    // }
    pub fn parse(&mut self, det: &CharsetDetector) -> i32 {
        self.parse_space(det, 0x20)
    }

    // public int parse(CharsetDetector det, byte spaceCh) {
    pub fn parse_space(&mut self, det: &CharsetDetector, space_ch: u8) -> i32 {
        // this.spaceChar = spaceCh;
        self.space_char = space_ch;

        self.parse_characters(det);

        // TODO: Is this OK? The buffer could have ended in the middle of a word...
        // addByte(spaceChar);
        self.add_byte(self.space_char as i32);

        // double rawPercent = (double) hitCount / (double) ngramCount;
        let raw_percent = self.hit_count as f64 / self.ngram_count as f64;

        //                if (rawPercent <= 2.0) {
        //                    return 0;
        //                }

        // TODO - This is a bit of a hack to take care of a case
        // were we were getting a confidence of 135...
        // if (rawPercent > 0.33) {
        //     return 98;
        // }
        if raw_percent > 0.33 {
            return 98;
        }

        // return (int) (rawPercent * 300.0);
        (raw_percent * 300.0) as i32
    }
}

