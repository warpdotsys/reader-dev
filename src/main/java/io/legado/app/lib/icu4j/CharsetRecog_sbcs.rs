    fn parse_characters(&mut self, det: &CharsetDetector) {
        // int b;
        let mut b: i32;
        // boolean ignoreSpace = false;
        let mut ignore_space = false;

        // while ((b = nextByte(det)) >= 0) {
        loop {
            b = self.next_byte(det);
            if b < 0 {
                break;
            }
            // byte mb = byteMap[b];
            let mut mb = self.byte_map[b as usize];

            // TODO: 0x20 might not be a space in all character sets...
            // if (mb != 0) {
            //     if (!(mb == spaceChar && ignoreSpace)) {
            //         addByte(mb);
            //     }
            //
            //     ignoreSpace = (mb == spaceChar);
            // }
            if mb != 0 {
                if !(mb == self.space_char && ignore_space) {
                    self.add_byte(mb as i32);
                }

                ignore_space = (mb == self.space_char);
            }
            // if (alef != (byte) 0x00) {
            //     mb = byteMap[alef & 0xFF];
            //
            //     // TODO: 0x20 might not be a space in all character sets...
            //     if (mb != 0) {
            //         if (!(mb == spaceChar && ignoreSpace)) {
            //             addByte(mb);
            //         }
            //
            //         ignoreSpace = (mb == spaceChar);
            //     }
            //
            // }
            if self.alef != 0x00 {
                mb = self.byte_map[self.alef as usize];

                // TODO: 0x20 might not be a space in all character sets...
                if mb != 0 {
                    if !(mb == self.space_char && ignore_space) {
                        self.add_byte(mb as i32);
                    }

                    ignore_space = (mb == self.space_char);
                }
            }
        }
    }

