const dicts: Record<Lang, LangDict> = { zh, en }

function loadLang(): Lang {
  try {
    const raw = localStorage.getItem(LANG_KEY)
    if (raw === 'zh' || raw === 'en') return raw
  } catch {
    /* ignore */
  }
  return 'zh'
}

/** 当前语言（ref——模板中经 t() 访问自动建立响应式依赖） */
export const lang = ref<Lang>(loadLang())

export function getLang(): Lang {
  return lang.value
}

export function setLang(l: Lang): void {
  lang.value = l
  try {
    localStorage.setItem(LANG_KEY, l)
  } catch {
    /* ignore */
  }
  applyDocLang()
}

/** 同步 <html lang>（路由标题由 router.afterEach 负责；语言切换时 App.vue 会重算标题） */
export function applyDocLang(): void {
  if (typeof document === 'undefined') return
  document.documentElement.lang = lang.value === 'zh' ? 'zh-CN' : 'en'
}

/** 翻译：t('key') / t('key', { n: 3 })——{name} 占位符替换；缺失回退 zh，再缺失原样返回 key */
export function t(key: string, params?: Params): string {
  const dict = dicts[lang.value]
  let text = dict[key] ?? zh[key] ?? key
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.split(`{${k}}`).join(String(v))
    }
  }
  return text
}
